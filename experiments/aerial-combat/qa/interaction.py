"""Focused acceptance checks using actual browser input and native animation clips."""
import asyncio,json,os
from pathlib import Path
from playwright.async_api import async_playwright

async def main():
 out=Path('aerial-results/interaction');out.mkdir(parents=True,exist_ok=True)
 report={'checks':{},'errors':[]}
 async with async_playwright() as pw:
  opts={'headless':True,'args':['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']}
  if Path('/usr/bin/chromium').exists():opts['executable_path']='/usr/bin/chromium'
  if os.environ.get('HTTPS_PROXY'):opts['proxy']={'server':os.environ['HTTPS_PROXY'],'bypass':'localhost,127.0.0.1'}
  browser=await pw.chromium.launch(**opts);page=await browser.new_page(viewport={'width':960,'height':540},has_touch=True,ignore_https_errors=True)
  page.on('pageerror',lambda e:report['errors'].append(str(e)))
  page.on('console',lambda m:report['errors'].append(m.text) if m.type=='error' and any(t in m.text for t in ['WebGL','INVALID_OPERATION','OUT_OF_MEMORY']) else None);page.set_default_timeout(120000)
  await page.goto(os.environ.get('VISUAL_BASE_URL','http://127.0.0.1:4181')+'/experiments/aerial-combat/',wait_until='domcontentloaded');await page.wait_for_function('window.AerialLab?.ready')
  async def js(code):return await page.evaluate(code)
  await js('AerialLab.ai(false);AerialLab.step();AerialLab.reset()')
  # Five complete five-hit chains using the real input buffer, not forced combo indices.
  report['chains']=await js('''(()=>{const chains=[];for(let cycle=0;cycle<5;cycle++){
   AerialLab.reset();AerialLab.pose(0,0,1.7);AerialLab.target(0,0,0);const start=AerialLab.log.length;AerialLab.command('attack');
   let queued=false,previous=null;for(let frame=0;frame<290;frame++){const c=AerialLab.snapshot().combo;
    if(c&&c.id!==previous){previous=c.id;queued=false;}
    if(c&&!queued&&c.id!=='AirSword_4'&&c.t>AerialLab.rig().moves.find(m=>m.id===c.id).buffer+.01){AerialLab.command('attack');queued=true;}
    AerialLab.step(1/60,1,false);
   }chains.push(AerialLab.log.slice(start).filter(e=>e.type==='attack'||e.type==='contact'));
  }return chains;})()''')
  report['checks']['fiveFullChains']=all([e['move'] for e in chain if e['type']=='attack']==[f'AirSword_{i}' for i in range(5)] for chain in report['chains'])
  report['latencyMs']=[e['latencyMs'] for c in report['chains'] for e in c if e['type']=='attack']
  # While a blocking cast runs, dash and jump cannot cancel it. Death still reaches floor.
  report['checks']['blockingCast']=await js("(()=>{AerialLab.reset();AerialLab.step(1/60,120);AerialLab.command('magic');return !AerialLab.command('dash')&&!AerialLab.command('jump');})()")
  report['death']=await js("AerialLab.reset();AerialLab.command('jump');AerialLab.step(1/60,15);AerialLab.setHP(0);AerialLab.step(1/60,120);AerialLab.snapshot()")
  report['checks']['deathLands']=report['death']['p']['y']==0 and report['death']['combo'] is None
  await js('AerialLab.reset();AerialLab.ai(false);AerialLab.step()')
  report['checks']['restartRestoresControl']=await js("AerialLab.command('jump')")
  await js('AerialLab.step(1/60,120)')
  # Genuine touchscreen tap, compare only events generated by this tap.
  before=await js('AerialLab.log.length');box=await page.locator('[data-action="attack"]').bounding_box()
  await page.touchscreen.tap(box['x']+box['width']/2,box['y']+box['height']/2)
  report['touchEvents']=await js(f'AerialLab.log.slice({before})')
  report['checks']['touchAttack']=any(e['type']=='command' and e['kind']=='attack' and e['accepted'] for e in report['touchEvents'])
  await js('AerialLab.step(1/60,120)')
  # Mouse drag, actual joystick pointer capture, and independent touch sensitivity.
  yaw=await js('AerialLab.snapshot().camera.yaw');await page.mouse.move(500,240);await page.mouse.down();await page.mouse.move(620,240,steps=6);await page.mouse.up()
  report['checks']['freeCamera']=abs(await js('AerialLab.snapshot().camera.yaw')-yaw)>.5
  box=await page.locator('#joystick').bounding_box();x,y=box['x']+box['width']/2,box['y']+box['height']/2
  before=await js('AerialLab.snapshot().p');await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+30,y);await js('AerialLab.step(1/60,30)');await page.mouse.up();after=await js('AerialLab.snapshot().p')
  report['checks']['joystick']=abs(after['x']-before['x'])+abs(after['z']-before['z'])>.5
  report['cameraSensitivity']=[]
  for width,height in [(960,540),(393,852)]:
   await page.set_viewport_size({'width':width,'height':height})
   for sensitivity in [.3,2]:
    await js(f'document.getElementById("touch").value={sensitivity}')
    before=await js('AerialLab.snapshot().camera.yaw')
    # CDP dispatches real touch pointers, including the browser pointer-capture path.
    cdp=await page.context.new_cdp_session(page)
    await cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':width*.45,'y':height*.45}]})
    await cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':width*.65,'y':height*.45}]})
    await cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
    after=await js('AerialLab.snapshot().camera.yaw');report['cameraSensitivity'].append({'width':width,'sensitivity':sensitivity,'delta':abs(after-before)})
    await cdp.detach()
  values=report['cameraSensitivity'];report['checks']['independentTouchSensitivity']=values[1]['delta']>values[0]['delta']*3 and values[3]['delta']>values[2]['delta']*3
  # Render ghosts while visible to warm GPU buffers; then compare after another 50 dashes.
  await page.set_viewport_size({'width':960,'height':540})
  report['pool']=await js("(()=>{AerialLab.reset();AerialLab.pose(-8,0,8);for(let warm=0;warm<3;warm++){AerialLab.command('dash');AerialLab.step(.05);AerialLab.step(.5);}const before=AerialLab.snapshot();for(let i=0;i<50;i++){AerialLab.step(.5);AerialLab.pose(-8,0,8);AerialLab.command('dash');AerialLab.step(.05);}return{before,after:AerialLab.snapshot()};})()")
  report['checks']['warmPoolStable']=report['pool']['before']['resources']==report['pool']['after']['resources'] and report['pool']['after']['ghosts']['active']<=3
  # Frame-by-frame workload includes contact, trails and shadows, not only idle frames.
  report['renderComparison']=[]
  for mode in [False,True]:
   for quality in ['low','high']:
    for hz in [30,60]:
     frames=await js(f"(()=>{{AerialLab.mode({str(mode).lower()});AerialLab.quality('{quality}');AerialLab.ai(false);AerialLab.pose(0,0,1.7);AerialLab.target(0,0,0);AerialLab.command('attack');const f=[];for(let i=0;i<{hz};i++)f.push(AerialLab.step(1/{hz}));return f.map(x=>({{draw:x.draw,resources:x.resources,p:x.p}}));}})()")
     report['renderComparison'].append({'prototype':mode,'quality':quality,'hz':hz,'frames':frames})
  report['checks']['finiteFrames']=all(f['p']['y']>=0 for case in report['renderComparison'] for f in case['frames'])
  await browser.close()
 report['status']='passed' if all(report['checks'].values()) and not report['errors'] else 'requires-fixes'
 (out/'report.json').write_text(json.dumps(report,indent=2));print(json.dumps({'status':report['status'],'checks':report['checks'],'errors':report['errors']}),flush=True)
 if report['status']!='passed':raise RuntimeError('Interaction acceptance failed')

asyncio.run(main())
